/** Vector-style app logo drawn in code (used on splash and About). */
class LogoView(ctx: Context) : View(ctx) {
    private val bg = Paint(Paint.ANTI_ALIAS_FLAG)
    private val ring = Paint(Paint.ANTI_ALIAS_FLAG).apply { style = Paint.Style.STROKE; strokeCap = Paint.Cap.ROUND }
    private val needle = Paint(Paint.ANTI_ALIAS_FLAG).apply { color = Color.WHITE }
    private val txt = Paint(Paint.ANTI_ALIAS_FLAG).apply {
        color = Color.WHITE; textAlign = Paint.Align.CENTER; typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
    }
    private val r = RectF()
    private val p = Path()

    override fun onMeasure(w: Int, h: Int) {
        val s = MeasureSpec.getSize(w)
        setMeasuredDimension(s, s)
    }

    override fun onDraw(c: Canvas) {
        val s = minOf(width, height).toFloat()
        val cx = width / 2f
        val cy = height / 2f
        bg.shader = RadialGradient(cx, cy * 0.8f, s / 2, Color.parseColor("#24405E"), Color.parseColor("#0B0F13"), Shader.TileMode.CLAMP)
        c.drawCircle(cx, cy, s / 2 * 0.96f, bg)
        val rr = s * 0.32f
        ring.strokeWidth = s * 0.07f
        ring.shader = LinearGradient(cx - rr, 0f, cx + rr, 0f,
            intArrayOf(Color.parseColor("#00E5FF"), Color.parseColor("#2F7FD0"), Color.parseColor("#FF5252")), null, Shader.TileMode.CLAMP)
        r.set(cx - rr, cy - rr, cx + rr, cy + rr)
        c.drawArc(r, 140f, 260f, false, ring)
        p.reset()
        p.moveTo(cx - s * 0.03f, cy + s * 0.02f)
        p.lineTo(cx + rr * 0.72f, cy - rr * 0.62f)
        p.lineTo(cx + s * 0.03f, cy + s * 0.03f)
        p.close()
        c.drawPath(p, needle)
        c.drawCircle(cx, cy, s * 0.045f, needle)
        txt.textSize = s * 0.13f
        c.drawText("OBD", cx, cy + rr * 0.95f, txt)
    }
}
