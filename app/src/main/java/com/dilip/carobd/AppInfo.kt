/** Vector-style app logo drawn in code (used on splash and About). */
class LogoView(ctx: Context) : View(ctx) {
    private val bg = Paint(Paint.ANTI_ALIAS_FLAG)
    private val ring = Paint(Paint.ANTI_ALIAS_FLAG).apply { style = Paint.Style.STROKE; strokeCap = Paint.Cap.ROUND }
    private val needle = Paint(Paint.ANTI_ALIAS_FLAG).apply { color = Color.WHITE }
    private val txt = Paint(Paint.ANTI_ALIAS_FLAG).apply {
        color = Color.WHITE; textAlign = Paint.Align.CENTER; typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
    }
    private val r = RectF()
    private val p = Path()

    override fun onMeasure(w: Int, h: Int) {
        val s = MeasureSpec.getSize(w)
        setMeasuredDimension(s, s)
    }

    private var logoBmp: android.graphics.Bitmap? = null
    private val logoPaint = Paint(Paint.ANTI_ALIAS_FLAG or Paint.FILTER_BITMAP_FLAG)

    override fun onDraw(c: Canvas) {
        if (logoBmp == null) {
            val id = resources.getIdentifier("app_logo", "drawable", context.packageName)
            if (id != 0) logoBmp = try { android.graphics.BitmapFactory.decodeResource(resources, id) } catch (_: Exception) { null }
        }
        logoBmp?.let { c.drawBitmap(it, null, RectF(0f, 0f, width.toFloat(), height.toFloat()), logoPaint); return }
        val s = minOf(width, height).toFloat()
        val cx = width / 2f
        val cy = height / 2f
        bg.shader = RadialGradient(cx, cy * 0.8f, s / 2, Color.parseColor("#24405E"), Color.parseColor("#0B0F13"), Shader.TileMode.CLAMP)
        c.drawCircle(cx, cy, s / 2 * 0.96f, bg)
        // OBD-II port with heartbeat line (matches the launcher icon)
        val u = s / 108f
        val ox = cx - s / 2; val oy = cy - s / 2
        fun X(v: Float) = ox + v * u
        fun Y(v: Float) = oy + v * u
        ring.shader = null
        ring.strokeWidth = 4.5f * u; ring.strokeJoin = Paint.Join.ROUND; ring.color = Color.parseColor("#27D3FF")
        p.reset()
        p.moveTo(X(27f), Y(34f)); p.lineTo(X(81f), Y(34f)); p.lineTo(X(77f), Y(62f)); p.lineTo(X(73f), Y(65f))
        p.lineTo(X(35f), Y(65f)); p.lineTo(X(31f), Y(62f)); p.lineTo(X(25f), Y(37f)); p.close()
        needle.color = Color.parseColor("#0E1B2A"); c.drawPath(p, needle)
        c.drawPath(p, ring)
        for (i in 0 until 8) {
            needle.color = Color.WHITE; c.drawCircle(X(35f + 38f * i / 7f), Y(44f), 1.9f * u, needle)
            needle.color = Color.parseColor("#FFB020"); c.drawCircle(X(38f + 32f * i / 7f), Y(55f), 1.9f * u, needle)
        }
        ring.color = Color.parseColor("#2EE59D"); ring.strokeWidth = 4f * u
        p.reset()
        p.moveTo(X(22f), Y(81f)); p.lineTo(X(40f), Y(81f)); p.lineTo(X(46f), Y(72f)); p.lineTo(X(55f), Y(90f))
        p.lineTo(X(62f), Y(78f)); p.lineTo(X(68f), Y(81f)); p.lineTo(X(86f), Y(81f))
        ring.style = Paint.Style.STROKE; c.drawPath(p, ring)
    }
}
